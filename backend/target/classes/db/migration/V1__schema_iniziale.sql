-- ════════════════════════════════════════════════════════════════════════════
-- Schema iniziale Simulatore Bollette Luce — modello a due sorgenti dati
-- Compatibile PostgreSQL 16 e H2 (modalita PostgreSQL, per i test).
-- ════════════════════════════════════════════════════════════════════════════

-- ── Parametri ARERA legacy (vecchio motore /api/simulazioni) ──────────────────
CREATE TABLE parametri_arera (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_parametro  VARCHAR(255)   NOT NULL,
    descrizione     VARCHAR(255)   NOT NULL,
    valore          NUMERIC(12, 8) NOT NULL,
    unita_misura    VARCHAR(255)   NOT NULL,
    valido_dal      DATE           NOT NULL,
    valido_al       DATE,
    created_at      TIMESTAMP
);

-- ── PUN mensile ───────────────────────────────────────────────────────────────
CREATE TABLE pun_mensili (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anno           INTEGER        NOT NULL,
    mese           INTEGER        NOT NULL,
    pun_monorario  NUMERIC(10, 6),
    punf1          NUMERIC(10, 6),
    punf2          NUMERIC(10, 6),
    punf3          NUMERIC(10, 6),
    punf23         NUMERIC(10, 6),
    created_at     TIMESTAMP
);

-- ── Offerte del gestore ───────────────────────────────────────────────────────
CREATE TABLE offerte (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_fornitore      VARCHAR(255)   NOT NULL,
    nome_offerta        VARCHAR(255)   NOT NULL,
    tipo_offerta        VARCHAR(255)   NOT NULL,
    tipo_tariffa        VARCHAR(255)   NOT NULL,
    prezzo_fissof0      NUMERIC(10, 6),
    prezzo_fissof1      NUMERIC(10, 6),
    prezzo_fissof23     NUMERIC(10, 6),
    prezzo_fissof2      NUMERIC(10, 6),
    prezzo_fissof3      NUMERIC(10, 6),
    spread_punf0        NUMERIC(10, 6),
    spread_punf1        NUMERIC(10, 6),
    spread_punf23       NUMERIC(10, 6),
    spread_punf2        NUMERIC(10, 6),
    spread_punf3        NUMERIC(10, 6),
    pcv_annuo           NUMERIC(10, 2),
    condizioni_speciali VARCHAR(1000),
    attiva              BOOLEAN,
    created_at          TIMESTAMP,
    updated_at          TIMESTAMP
);

-- ── Voci di corrispettivo dell'offerta (origine OFFERTA) ──────────────────────
CREATE TABLE voci_corrispettivo (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    offerta_id         BIGINT,
    descrizione        VARCHAR(255)   NOT NULL,
    categoria          VARCHAR(255)   NOT NULL,
    base               VARCHAR(255)   NOT NULL,
    origine            VARCHAR(255)   NOT NULL,
    corrispettivo      NUMERIC(16, 8) NOT NULL,
    aliquota_iva       NUMERIC(6, 4),
    unita_misura       VARCHAR(20),
    ordine             INTEGER,
    attiva             BOOLEAN,
    variabile_per_mese BOOLEAN,
    numero_mese        INTEGER,
    CONSTRAINT fk_voce_offerta FOREIGN KEY (offerta_id) REFERENCES offerte (id)
);

-- ── Simulazioni (vecchio motore) ──────────────────────────────────────────────
CREATE TABLE simulazioni (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                  VARCHAR(255)   NOT NULL,
    tipo_cliente          VARCHAR(255)   NOT NULL,
    potenza_contrattuale  VARCHAR(255)   NOT NULL,
    consumo_totale_kwh    NUMERIC(10, 2) NOT NULL,
    consumof1             NUMERIC(10, 2),
    consumof2             NUMERIC(10, 2),
    consumof3             NUMERIC(10, 2),
    spesa_materia_energia NUMERIC(12, 4),
    spesa_trasporto       NUMERIC(12, 4),
    spesa_oneri_sistema   NUMERIC(12, 4),
    spesa_accise          NUMERIC(12, 4),
    spesa_iva             NUMERIC(12, 4),
    totale_bimestrale     NUMERIC(12, 4),
    totale_annuale        NUMERIC(12, 4),
    prezzo_medio_kwh      NUMERIC(10, 6),
    created_at            TIMESTAMP,
    updated_at            TIMESTAMP
);

-- ── SORGENTE B: Parametri del gestore ─────────────────────────────────────────
CREATE TABLE parametri_gestore (
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_profilo               VARCHAR(255)  NOT NULL UNIQUE,
    descrizione                VARCHAR(255),
    predefinito                BOOLEAN,
    nome_gestore               VARCHAR(255),
    valido_dal                 DATE,
    valido_al                  DATE,
    livello_tensione_default   VARCHAR(255),
    percentuale_perdite        NUMERIC(8, 6),
    arrotonda_perdite          BOOLEAN,
    trasporto_kw_mese          NUMERIC(14, 8),
    trasporto_pod_mese         NUMERIC(14, 8),
    trasporto_kwh              NUMERIC(14, 8),
    asos_quota_fissa           NUMERIC(14, 8),
    asos_quota_variabile       NUMERIC(14, 8),
    arim_quota_variabile       NUMERIC(14, 8),
    accisa_domestico           NUMERIC(14, 8),
    accisa_non_domestico       NUMERIC(14, 8),
    applica_soglia_esenzione   BOOLEAN,
    soglia_esenzione_kwh_anno  NUMERIC(12, 2),
    soglia_massima_kwh_anno    NUMERIC(12, 2),
    iva_domestico              NUMERIC(6, 4),
    iva_non_domestico          NUMERIC(6, 4),
    usa_aliquota_iva_bolletta  BOOLEAN,
    altre_partite_in_imponibile BOOLEAN,
    corr_mercato_capacita      NUMERIC(14, 8),
    corr_dis_rtn               NUMERIC(14, 8),
    corr_int                   NUMERIC(14, 8),
    corr_msd                   NUMERIC(14, 8),
    corr_ues_sicurezza         NUMERIC(14, 8),
    corr_sal                   NUMERIC(14, 8),
    corr_sbilanciamento        NUMERIC(14, 8),
    corr_aggregazione_misure   NUMERIC(14, 8),
    dispbt                     NUMERIC(14, 8),
    corr_gestione_capacita     NUMERIC(14, 8),
    commercializzazione_mese   NUMERIC(14, 8),
    pcv_variabile              NUMERIC(14, 8),
    spread_energia             NUMERIC(14, 8),
    created_at                 TIMESTAMP,
    updated_at                 TIMESTAMP
);

-- ── SORGENTE A: Bollette concorrenti ──────────────────────────────────────────
CREATE TABLE bollette_concorrenti (
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_fattura             VARCHAR(255),
    data_fattura               DATE,
    periodo_dal                DATE,
    periodo_al                 DATE,
    nome_fornitore             VARCHAR(255) NOT NULL,
    nome_offerta               VARCHAR(255),
    codice_offerta             VARCHAR(255),
    ragione_sociale            VARCHAR(255),
    indirizzo_fornitura        VARCHAR(255),
    pod                        VARCHAR(255),
    tipologia_cliente          VARCHAR(255),
    opzione_tariffaria         VARCHAR(255),
    potenza_impegnata          NUMERIC(6, 2),
    potenza_disponibile        NUMERIC(6, 2),
    livello_tensione           VARCHAR(255),
    fatturato_materia_energia  NUMERIC(12, 2),
    fatturato_trasporto        NUMERIC(12, 2),
    fatturato_oneri_sistema    NUMERIC(12, 2),
    fatturato_altre_partite    NUMERIC(12, 2),
    fatturato_imposte          NUMERIC(12, 2),
    fatturato_iva              NUMERIC(12, 2),
    fatturato_imponibile       NUMERIC(12, 2),
    fatturato_totale           NUMERIC(12, 2),
    aliquota_iva_applicata     NUMERIC(6, 4),
    note                       VARCHAR(1000),
    created_at                 TIMESTAMP,
    updated_at                 TIMESTAMP
);

-- ── Mesi della bolletta (consumi F1/F2/F3) ────────────────────────────────────
CREATE TABLE mesi_bolletta (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bolletta_id            BIGINT,
    numero_mese            INTEGER        NOT NULL,
    nome_mese              VARCHAR(255),
    mese                   INTEGER,
    anno                   INTEGER,
    consumof1              NUMERIC(12, 2) NOT NULL,
    consumof2              NUMERIC(12, 2) NOT NULL,
    consumof3              NUMERIC(12, 2) NOT NULL,
    lettura_attualef1      NUMERIC(12, 2),
    lettura_precedentef1   NUMERIC(12, 2),
    lettura_attualef2      NUMERIC(12, 2),
    lettura_precedentef2   NUMERIC(12, 2),
    lettura_attualef3      NUMERIC(12, 2),
    lettura_precedentef3   NUMERIC(12, 2),
    CONSTRAINT fk_mese_bolletta FOREIGN KEY (bolletta_id) REFERENCES bollette_concorrenti (id)
);

-- ── Altre partite della bolletta ──────────────────────────────────────────────
CREATE TABLE altre_partite (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bolletta_id  BIGINT,
    descrizione  VARCHAR(255)   NOT NULL,
    dal          DATE,
    al           DATE,
    importo      NUMERIC(12, 2) NOT NULL,
    aliquota_iva NUMERIC(6, 4),
    soggetta_iva BOOLEAN,
    ordine       INTEGER,
    CONSTRAINT fk_partita_bolletta FOREIGN KEY (bolletta_id) REFERENCES bollette_concorrenti (id)
);

-- ── Confronti salvati (storico) ───────────────────────────────────────────────
CREATE TABLE confronti (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bolletta_concorrente_id  BIGINT,
    nome_concorrente         VARCHAR(255),
    offerta_gestore_id       BIGINT,
    nome_offerta_gestore     VARCHAR(255),
    parametri_gestore_id     BIGINT,
    nome_profilo_parametri   VARCHAR(255),
    gestore_materia_energia  NUMERIC(12, 4),
    gestore_trasporto        NUMERIC(12, 4),
    gestore_oneri_sistema    NUMERIC(12, 4),
    gestore_imposte          NUMERIC(12, 4),
    gestore_altre_partite    NUMERIC(12, 4),
    gestore_imponibile       NUMERIC(12, 4),
    gestore_iva              NUMERIC(12, 4),
    gestore_totale           NUMERIC(12, 4),
    concorrente_totale       NUMERIC(12, 2),
    risparmio_bimestrale     NUMERIC(12, 2),
    risparmio_annuale        NUMERIC(12, 2),
    created_at               TIMESTAMP
);
